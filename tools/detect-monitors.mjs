// Monitor geometry -> config/monitors.local.js, on either platform.
//   Windows: delegates to tools/detect-monitors.ps1
//   GNOME:   asks Mutter over D-Bus (org.gnome.Mutter.DisplayConfig.GetCurrentState)
//
//   node tools/detect-monitors.mjs [--site work]     (default: this machine's site)
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
try { await import(pathToFileURL(path.join(ROOT, "config/site.local.js")).href); } catch {}
await import(pathToFileURL(path.join(ROOT, "config/atlas.config.js")).href);
const args = process.argv.slice(2);
const site = args.includes("--site") ? args[args.indexOf("--site") + 1] : globalThis.ATLAS_CONFIG.defaultSite;

if (process.platform === "win32") {
  execFileSync("powershell", ["-ExecutionPolicy", "Bypass", "-File", path.join(ROOT, "tools/detect-monitors.ps1"), "-Site", site], { stdio: "inherit" });
  process.exit(0);
}

const state = execFileSync("gdbus", ["call", "--session", "--dest", "org.gnome.Mutter.DisplayConfig",
  "--object-path", "/org/gnome/Mutter/DisplayConfig", "--method", "org.gnome.Mutter.DisplayConfig.GetCurrentState"], { encoding: "utf8" });

// Physical monitors: connector -> current mode size.
const modeOf = {};
const physical = state.slice(0, state.indexOf("], [(")); // logical monitors start after the physical list
for (const chunk of physical.split("(('").slice(1)) {
  const cur = /\('[^']*', (\d+), (\d+), [\d.]+, [\d.]+, \[[^\]]*\], \{'is-current': <true>/.exec(chunk);
  if (cur) modeOf[chunk.slice(0, chunk.indexOf("'"))] = [Number(cur[1]), Number(cur[2])];
}
// Logical monitors: (x, y, scale, transform, primary, [(connector, ...)], props)
const logicalMode = /'layout-mode': <uint32 (\d)>/.exec(state)?.[1] !== "2"; // 1 = logical px, 2 = physical
const list = [];
for (const m of state.matchAll(/\((-?\d+), (-?\d+), ([\d.]+), (?:uint32 )?(\d+), (true|false), \[\('([^']+)'/g)) {
  const [, x, y, scale, transform, primary, device] = m;
  let [w, h] = modeOf[device] || [0, 0];
  if (Number(transform) % 2 === 1) [w, h] = [h, w]; // 90/270 rotations
  if (logicalMode) { w = Math.round(w / Number(scale)); h = Math.round(h / Number(scale)); }
  list.push({ device, x: Number(x), y: Number(y), w, h, primary: primary === "true" });
}
list.sort((a, b) => a.x - b.x);
if (!list.length) { console.error("no monitors parsed from Mutter state"); process.exit(1); }

const body = `// Generated by tools/detect-monitors.mjs on ${new Date().toISOString().slice(0, 19)}. Do not edit; re-run to refresh.\n` +
  `(function(g){ (g.ATLAS_MONITORS = g.ATLAS_MONITORS || {})[${JSON.stringify(site)}] = ${JSON.stringify(list)}; })(typeof window !== 'undefined' ? window : globalThis);\n`;
fs.writeFileSync(path.join(ROOT, "config/monitors.local.js"), body);
console.log("wrote config/monitors.local.js:", JSON.stringify(list));
